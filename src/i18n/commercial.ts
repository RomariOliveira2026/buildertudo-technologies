export const commercialCopy: Record<Locale, CommercialCopy> = { en, es, 'pt-BR': ptBR }

export function getCommercialCopy(locale: Locale) {
  return commercialCopy[locale]
}

export function getCommercialContactTypes(locale: Locale) {
  const types = commercialCopy[locale].form.types
  return [types.express, types.business, types.premium, types.landing, types.custom, types.unknown] as const
}

export function getPortfolioProjectDescription(locale: Locale, slug: string, fallback: string) {
  const projects = commercialCopy[locale].portfolio.projects
  return projects[slug as keyof typeof projects] ?? fallback
}
